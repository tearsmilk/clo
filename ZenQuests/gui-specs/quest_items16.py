def C(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)

def grid(rows):
    assert len(rows) == 16, len(rows)
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0)); p = im.load()
    for y, row in enumerate(rows):
        assert len(row) == 32, (y, len(row), row)
        for x in range(16):
            t = row[2 * x:2 * x + 2]
            if t != '..': p[x, y] = C(PAL[t[0]][int(t[1])])
    return im

